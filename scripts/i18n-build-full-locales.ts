/**
 * Build full-coverage locale catalogs (fr, es, de, ar, zh-Hans, hi) from translation-memory
 * data files in scripts/i18n-data/*.json (arrays of [en, fr, es, de, ar, zh-Hans, hi]).
 *
 * For every leaf in enResources, looks up the English string in the matching namespace's
 * dictionary and substitutes the translation. Leaves with no dictionary entry fall back to
 * English and are reported as "missing" so translators can top them up incrementally.
 *
 * Writes src/i18n/catalogs/locales/{code}.ts (one full resource tree per locale) and a
 * scripts/i18n-coverage-report.json summary.
 *
 * Run: npx tsx scripts/i18n-build-full-locales.ts
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { enResources } from "../src/i18n/catalogs/en.ts";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DATA_DIR = path.join(__dirname, "i18n-data");

const LOCALES = ["fr", "es", "de", "ar", "zh-Hans", "hi"] as const;
type LocaleCode = (typeof LOCALES)[number];
const LOCALE_INDEX: Record<LocaleCode, number> = {
  fr: 1,
  es: 2,
  de: 3,
  ar: 4,
  "zh-Hans": 5,
  hi: 6,
};

const NAMESPACES = ["common", "nav", "auth", "errors", "roles", "pages", "public"] as const;
type Namespace = (typeof NAMESPACES)[number];

/** namespace -> EN string -> [fr, es, de, ar, zh-Hans, hi] */
const dict: Record<Namespace, Map<string, string[]>> = {
  common: new Map(),
  nav: new Map(),
  auth: new Map(),
  errors: new Map(),
  roles: new Map(),
  pages: new Map(),
  public: new Map(),
};

function loadNamespaceFiles(ns: Namespace) {
  // Accept either "<ns>.json" or "<ns>-partNN.json" so large namespaces (pages) can be split.
  const files = readdirSync(DATA_DIR).filter(
    (f) => (f === `${ns}.json` || f.startsWith(`${ns}-`)) && f.endsWith(".json"),
  );
  for (const file of files) {
    const rows: string[][] = JSON.parse(readFileSync(path.join(DATA_DIR, file), "utf8"));
    for (const row of rows) {
      const [en, ...rest] = row;
      if (dict[ns].has(en)) continue; // first occurrence wins; avoid accidental dupes overriding
      dict[ns].set(en, rest);
    }
  }
}

for (const ns of NAMESPACES) loadNamespaceFiles(ns);

function translateTree(node: any, ns: Namespace, localeIdx: number, missing: string[], keyPath: string): any {
  if (node && typeof node === "object" && !Array.isArray(node)) {
    const out: Record<string, any> = {};
    for (const [k, v] of Object.entries(node)) {
      out[k] = translateTree(v, ns, localeIdx, missing, keyPath ? `${keyPath}.${k}` : k);
    }
    return out;
  }
  if (typeof node === "string") {
    const row = dict[ns].get(node);
    const translated = row?.[localeIdx - 1];
    if (translated) return translated;
    missing.push(keyPath);
    return node; // fallback to English; runtime deep-merge would do this anyway
  }
  return node;
}

function tsLiteral(value: any, indent = 0): string {
  const pad = "  ".repeat(indent);
  const padIn = "  ".repeat(indent + 1);
  if (typeof value === "string") return JSON.stringify(value);
  if (value && typeof value === "object" && !Array.isArray(value)) {
    const entries = Object.entries(value)
      .map(([k, v]) => `${padIn}${JSON.stringify(k)}: ${tsLiteral(v, indent + 1)},`)
      .join("\n");
    return `{\n${entries}\n${pad}}`;
  }
  return JSON.stringify(value);
}

mkdirSync(path.join(__dirname, "../src/i18n/catalogs/locales"), { recursive: true });

const report: Record<string, Record<string, number>> = {};

for (const code of LOCALES) {
  const localeIdx = LOCALE_INDEX[code];
  const missingByNs: Record<string, string[]> = {};
  const tree: Record<string, any> = {};
  for (const ns of NAMESPACES) {
    const missing: string[] = [];
    tree[ns] = translateTree((enResources as any)[ns], ns, localeIdx, missing, "");
    missingByNs[ns] = missing;
  }

  const varName = code.replace(/[-]([a-zA-Z])/g, (_, c) => c.toUpperCase()) + "Resources";
  const body = `/** AUTO-GENERATED by scripts/i18n-build-full-locales.ts — do not hand-edit.
 * Source of truth for content lives in scripts/i18n-data/*.json (translation memory).
 * Re-run: npx tsx scripts/i18n-build-full-locales.ts
 */
export const ${varName} = ${tsLiteral(tree)} as const;
`;
  writeFileSync(path.join(__dirname, `../src/i18n/catalogs/locales/${code}.ts`), body);

  report[code] = {};
  let totalMissing = 0;
  for (const ns of NAMESPACES) {
    report[code][ns] = missingByNs[ns].length;
    totalMissing += missingByNs[ns].length;
  }
  report[code].__totalMissing = totalMissing;
  console.log(`${code}: wrote locales/${code}.ts — missing leaves: ${totalMissing}`);
  for (const ns of NAMESPACES) {
    if (missingByNs[ns].length > 0) {
      console.log(`  ${ns}: ${missingByNs[ns].length} missing (e.g. ${missingByNs[ns].slice(0, 3).join(", ")})`);
    }
  }
}

writeFileSync(path.join(__dirname, "i18n-coverage-report.json"), JSON.stringify(report, null, 2));
console.log("\nWrote scripts/i18n-coverage-report.json");
