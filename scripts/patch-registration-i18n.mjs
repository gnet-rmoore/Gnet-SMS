for (const [locale, cfg] of Object.entries(blocks)) {
  const file = path.join(localesDir, `${locale}.ts`);
  let src = fs.readFileSync(file, "utf8");

  if (!src.includes('"registrationWorkflow"')) {
    const oldLine = src.match(/      "registrationsSubtitle": "[^"]+",\n      "reports":/);
    if (!oldLine) {
      console.error(`Skip ${locale}: anchor not found`);
      continue;
    }
    src = src.replace(
      /      "registrationsSubtitle": "[^"]+",\n      "reports":/,
      `${cfg.insert},\n      "reports":`
    );
  }

  if (!src.includes('"approve":')) {
    src = src.replace(
      /    "rejected": "[^"]+",\n    "paid":/,
      `    "rejected": "${cfg.reject === "Refuser" ? "Refusé" : src.match(/"rejected": "([^"]+)"/)?.[1] || "Rejected"}",\n    "approve": "${cfg.approve}",\n    "reject": "${cfg.reject}",\n    "paid":`
    );
  } else if (!src.includes('"reject":')) {
    src = src.replace(
      /    "approved": "[^"]+",\n    "rejected": "[^"]+",\n    "paid":/,
      (m) => m.replace('"paid":', `"approve": "${cfg.approve}",\n    "reject": "${cfg.reject}",\n    "paid":`)
    );
  }

  const calAnchor = /      "subtitle": "[^"]+",\n      "toast":/;
  if (calAnchor.test(src) && !src.includes('"today":')) {
    src = src.replace(
      calAnchor,
      `      "subtitle": "${src.match(/"calendar": \{[\s\S]*?"subtitle": "([^"]+)"/)?.[1] || "Events"}",\n      "today": "${cfg.calendarToday}",\n      "addEvent": "${cfg.calendarAddEvent}",\n      "toast":`
    );
  }

  fs.writeFileSync(file, src);
  console.log(`Patched ${locale}.ts`);
}
