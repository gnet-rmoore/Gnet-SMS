function deepMergePages(base: Record<string, unknown>, over: Record<string, unknown>): Record<string, unknown> {
  const out: Record<string, unknown> = { ...base };
  for (const [k, v] of Object.entries(over || {})) {
    const existing = out[k];
    if (
      existing &&
      v &&
      typeof existing === "object" &&
      typeof v === "object" &&
      !Array.isArray(existing) &&
      !Array.isArray(v)
    ) {
      out[k] = deepMergePages(
        existing as Record<string, unknown>,
        v as Record<string, unknown>
      );
    } else if (v !== undefined) {
      out[k] = v;
    }
  }
  return out;
}

